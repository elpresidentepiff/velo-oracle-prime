-- Additive, shadow-only evidence store for the Rich Context challenger.
-- Existing mutable formfav_runner_form rows remain evaluation-ineligible.

create table if not exists public.formfav_factual_captures (
    id bigint generated by default as identity primary key,
    provider_race_key text not null,
    provider_runner_number integer not null,
    provider_runner_name text not null,
    captured_at timestamptz not null,
    off_time_utc timestamptz,
    source_endpoint text not null,
    source_payload jsonb not null,
    source_payload_sha256 text not null check (source_payload_sha256 ~ '^[0-9a-f]{64}$'),
    capture_schema_version text not null,
    created_at timestamptz not null default now(),
    constraint formfav_factual_capture_content_unique unique
      (provider_race_key, provider_runner_number, captured_at, source_payload_sha256)
);

create index if not exists idx_formfav_factual_capture_race_time
  on public.formfav_factual_captures (provider_race_key, captured_at desc);

create table if not exists public.formfav_rich_context_manifests (
    id bigint generated by default as identity primary key,
    capture_id bigint not null references public.formfav_factual_captures(id),
    canonical_race_id text not null,
    canonical_runner_id text not null,
    race_match_method text not null,
    runner_match_method text not null,
    off_time_utc timestamptz not null,
    captured_before_off boolean not null,
    temporal_eligibility text not null check (temporal_eligibility in ('ELIGIBLE','INELIGIBLE')),
    identity_conflicts jsonb not null default '[]'::jsonb,
    feature_schema_version text not null,
    parser_version text not null,
    feature_families jsonb not null,
    family_coverage jsonb not null,
    missingness jsonb not null,
    banned_field_paths jsonb not null default '[]'::jsonb,
    derived_vector_sha256 text not null check (derived_vector_sha256 ~ '^[0-9a-f]{64}$'),
    training_eligible boolean not null default false,
    eligibility_reason text not null,
    code_sha text not null,
    created_at timestamptz not null default now(),
    constraint formfav_rich_context_manifest_unique unique
      (capture_id, canonical_race_id, canonical_runner_id, feature_schema_version, parser_version)
);

create index if not exists idx_formfav_rich_context_manifest_race
  on public.formfav_rich_context_manifests (canonical_race_id, created_at desc);
create index if not exists idx_formfav_rich_context_manifest_eligible
  on public.formfav_rich_context_manifests (training_eligible, created_at desc);

alter table public.formfav_factual_captures enable row level security;
alter table public.formfav_rich_context_manifests enable row level security;

revoke all on public.formfav_factual_captures from anon, authenticated;
revoke all on public.formfav_rich_context_manifests from anon, authenticated;
grant select, insert on public.formfav_factual_captures to service_role;
grant select, insert on public.formfav_rich_context_manifests to service_role;
grant usage, select on sequence public.formfav_factual_captures_id_seq to service_role;
grant usage, select on sequence public.formfav_rich_context_manifests_id_seq to service_role;

create or replace function public.reject_formfav_evidence_mutation()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  raise exception 'immutable FormFav evidence cannot be updated or deleted';
end;
$$;

revoke all on function public.reject_formfav_evidence_mutation() from public, anon, authenticated;
grant execute on function public.reject_formfav_evidence_mutation() to service_role;

create trigger formfav_factual_captures_immutable
before update or delete on public.formfav_factual_captures
for each row execute function public.reject_formfav_evidence_mutation();

create trigger formfav_rich_context_manifests_immutable
before update or delete on public.formfav_rich_context_manifests
for each row execute function public.reject_formfav_evidence_mutation();

comment on table public.formfav_factual_captures is
  'Append-only raw FormFav factual captures; no predictions or results permitted.';
comment on table public.formfav_rich_context_manifests is
  'Append-only shadow challenger provenance and eligibility manifests.';
